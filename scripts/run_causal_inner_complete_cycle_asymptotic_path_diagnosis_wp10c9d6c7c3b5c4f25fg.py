def _save_npz(path: Path, arrays: dict[str, np.ndarray]) -> None:
    with path.open("wb") as handle:
        np.savez(handle, **arrays)


def _update_catalog(summary: dict) -> None:
    helper = _helper()
    cold = parent.manifest.parent.manifest.parent.arclength._source()._post().manifest.transition.manifest.cold.manifest
    with cold.CANONICAL_MANIFEST.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    rows = [row for row in rows if row.get("case") != ARTIFACT]
    for path in sorted(CANONICAL_DIRECTORY.iterdir()):
        if path.is_file():
            rows.append({
                "case": ARTIFACT,
                "path": str(path.relative_to(ROOT)),
                "bytes": str(path.stat().st_size),
                "sha256": helper._sha(path),
                "scientific_status": "SUPPORTED" if summary["passed"] else "REJECTED",
            })
    with cold.CANONICAL_MANIFEST.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=("case", "path", "bytes", "sha256", "scientific_status"),
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)
    catalog = helper._read(cold.CANONICAL_SUMMARY)
    catalog.setdefault("artifacts", {})[ARTIFACT] = {
        "path": str(CANONICAL_DIRECTORY.relative_to(ROOT)),
        "classification": summary["classification"],
        "passed": summary["passed"],
    }
    catalog.update({
        "case_count": len({row["case"] for row in rows}),
        "file_count": len(rows),
        "total_bytes": sum(int(row["bytes"]) for row in rows),
        "all_payload_hashes_recorded": True,
        "latest_source_parent_commit": helper._git("rev-parse", "HEAD"),
        "latest_work_package": WORK_PACKAGE,
    })
    helper._write_json(cold.CANONICAL_SUMMARY, catalog)


def _canonicalize(metrics: dict, arrays: dict[str, np.ndarray]) -> dict:
    helper = _helper()
    if CANONICAL_DIRECTORY.exists() or REPORT_PATH.exists():
        raise RuntimeError("asymptotic diagnosis result already exists")
    CANONICAL_DIRECTORY.mkdir(parents=True)
    helper._write_json(CANONICAL_DIRECTORY / "diagnosis_metrics.json", metrics)
    helper._write_json(
        CANONICAL_DIRECTORY / "mathematical_architecture_decision.json",
        _architecture(metrics),
    )
    _save_npz(CANONICAL_DIRECTORY / "diagnosis_arrays.npz", arrays)
    summary = {
        "schema_version": SCHEMA_VERSION,
        "work_package": WORK_PACKAGE,
        "classification": metrics["classification"],
        "passed": bool(metrics["passed"]),
        "cycle_closure_authorized": False,
        "equilibrium_closure_authorized": False,
        "wide_arclength_continuation_manifest_authorized": bool(metrics["passed"]),
        "reduced_slow_evolution_authorized": False,
        "authorized_next": AUTHORIZED_NEXT if metrics["passed"] else None,
    }
    helper._write_json(CANONICAL_DIRECTORY / "summary.json", summary)
    helper._write_json(CANONICAL_DIRECTORY / "provenance.json", {
        "runner": THIS_RUNNER,
        "test": THIS_TEST,
        "implementation_commit": helper._git("rev-parse", "HEAD"),
        "implementation_tree": helper._git("rev-parse", "HEAD^{tree}"),
        "source_hashes": {
            THIS_RUNNER: helper._sha(ROOT / THIS_RUNNER),
            THIS_TEST: helper._sha(ROOT / THIS_TEST),
            parent.THIS_RUNNER: helper._sha(ROOT / parent.THIS_RUNNER),
        },
        "python": sys.version,
        "numpy": np.__version__,
        "platform": platform.platform(),
    })
    names = sorted(path.name for path in CANONICAL_DIRECTORY.iterdir())
    (CANONICAL_DIRECTORY / "SHA256SUMS.txt").write_text(
        "".join(
            f"{helper._sha(CANONICAL_DIRECTORY / name)}  {name}\n"
            for name in names
        ),
        encoding="utf-8",
    )
    values = metrics["gate_values"]
    h16 = metrics["hermite_replay"]["16"]
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(
        "\n".join((
            "# Complete-cycle asymptotic path diagnosis",
            "",
            f"Classification: `{metrics['classification']}`.",
            "",
            "The committed 16 ms original-free-field trajectory is an autonomous, open, low-curvature transient. Its Poincare section is strictly increasing, its path tortuosity is "
            f"`{values['path_tortuosity']:.6f}`, and its first POD direction contains `{values['first_pod_energy']:.6f}` of centered path energy.",
            "",
            f"The terminal speed remains `{values['terminal_speed_ratio']:.6f}` of its initial value and the net field-direction turn is only `{values['net_direction_turn_radians']:.6f}` rad. Neither a return cycle nor an equilibrium closure is supported.",
            "",
            f"Sliding cubic-Hermite replay over 4 ms spans has maximum coordinate defect `{h16['maximum_coordinate_defect']:.6e}` and rate defect `{h16['maximum_rate_defect']:.6e}`. This supports a definitions-only curvature-adaptive arclength continuation manifest with spans up to 4 ms.",
            "",
            "No new exact free-field evaluation, retraction, physical-time step, fixed-Q rate, reaction, nonlinear root, or BDF microstep was executed. Cycle averaging and reduced slow evolution remain unauthorized.",
            "",
        )),
        encoding="utf-8",
    )
    _update_catalog(summary)
    return summary


