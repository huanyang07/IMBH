def _hermite_replay(
    coordinates: np.ndarray,
    rates: np.ndarray,
    stride: int,
) -> tuple[dict, dict[str, np.ndarray]]:
    x = np.asarray(coordinates, dtype=float)
    f = np.asarray(rates, dtype=float)
    selected_stride = int(stride)
    coordinate_defects = []
    rate_defects = []
    window_starts = []
    sample_indices = []
    for start in range(len(x) - selected_stride):
        stop = start + selected_stride
        duration = selected_stride * MACRO_STEP_SECONDS
        displacement_norm = max(
            float(np.linalg.norm(x[stop] - x[start])),
            np.finfo(float).tiny,
        )
        for sample in range(start + 1, stop):
            phase = (sample - start) / selected_stride
            h00 = 2.0 * phase**3 - 3.0 * phase**2 + 1.0
            h10 = phase**3 - 2.0 * phase**2 + phase
            h01 = -2.0 * phase**3 + 3.0 * phase**2
            h11 = phase**3 - phase**2
            prediction = (
                h00 * x[start]
                + h10 * duration * f[start]
                + h01 * x[stop]
                + h11 * duration * f[stop]
            )
            dh00 = 6.0 * phase**2 - 6.0 * phase
            dh10 = 3.0 * phase**2 - 4.0 * phase + 1.0
            dh01 = -6.0 * phase**2 + 6.0 * phase
            dh11 = 3.0 * phase**2 - 2.0 * phase
            rate_prediction = (
                dh00 * x[start]
                + dh10 * duration * f[start]
                + dh01 * x[stop]
                + dh11 * duration * f[stop]
            ) / duration
            coordinate_defects.append(
                np.linalg.norm(prediction - x[sample]) / displacement_norm
            )
            rate_defects.append(
                np.linalg.norm(rate_prediction - f[sample])
                / max(float(np.linalg.norm(f[sample])), np.finfo(float).tiny)
            )
            window_starts.append(start)
            sample_indices.append(sample)
    coordinate_array = np.asarray(coordinate_defects)
    rate_array = np.asarray(rate_defects)
    metrics = {
        "stride": selected_stride,
        "duration_seconds": selected_stride * MACRO_STEP_SECONDS,
        "sample_count": int(len(coordinate_array)),
        "maximum_coordinate_defect": float(np.max(coordinate_array)),
        "maximum_rate_defect": float(np.max(rate_array)),
        "p95_coordinate_defect": float(np.quantile(coordinate_array, 0.95)),
        "p95_rate_defect": float(np.quantile(rate_array, 0.95)),
        "passed": bool(
            np.max(coordinate_array) <= MAXIMUM_HERMITE_COORDINATE_DEFECT
            and np.max(rate_array) <= MAXIMUM_HERMITE_RATE_DEFECT
        ),
    }
    arrays = {
        "coordinate_defects": coordinate_array,
        "rate_defects": rate_array,
        "window_starts": np.asarray(window_starts, dtype=int),
        "sample_indices": np.asarray(sample_indices, dtype=int),
    }
    return metrics, arrays


def _linear_target_forecast(
    time_seconds: np.ndarray,
    values: np.ndarray,
    target: float,
    count: int,
) -> dict:
    t = np.asarray(time_seconds, dtype=float)[-count:]
    y = np.asarray(values, dtype=float)[-count:]
    slope, intercept = np.polyfit(t, y, 1)
    crossing = None
    if slope != 0.0:
        candidate = float((target - intercept) / slope)
        if candidate > float(t[-1]):
            crossing = candidate
    return {
        "sample_count": int(count),
        "slope_per_second": float(slope),
        "forecast_target_time_seconds": crossing,
        "forecast_additional_seconds": (
            None if crossing is None else crossing - float(t[-1])
        ),
    }


def _evaluate(parent_lock: dict) -> tuple[dict, dict[str, np.ndarray]]:
    helper = _helper()
    cycle = helper._load_npz(
        parent.CANONICAL_DIRECTORY / "cycle_execution_arrays.npz"
    )
    witnesses = helper._load_npz(
        parent.CANONICAL_DIRECTORY / "exact_witness_arrays.npz"
    )
    trajectory = np.asarray(cycle["trajectory_coordinates"], dtype=float)
    macro = np.asarray(cycle["trajectory_macro82"], dtype=float)
    section_normal = np.asarray(cycle["section_normal470"], dtype=float)
    anchor_mask = np.asarray(witnesses["kinds"]).astype(str) == "anchor"
    anchor_coordinates = np.asarray(witnesses["coordinates"])[anchor_mask]
    anchor_rates = np.asarray(witnesses["coordinate_rates_per_s"])[anchor_mask]
    np.testing.assert_array_equal(anchor_coordinates, trajectory[:-1])
    if trajectory.shape != (65, 470) or anchor_rates.shape != (64, 470):
        raise RuntimeError("canonical complete-cycle trajectory shape changed")

    anchor_time = MACRO_STEP_SECONDS * np.arange(len(anchor_rates), dtype=float)
    trajectory_time = MACRO_STEP_SECONDS * np.arange(len(trajectory), dtype=float)
    section = (trajectory - trajectory[0]) @ section_normal
    section_velocity = anchor_rates @ section_normal
    speeds = np.linalg.norm(anchor_rates, axis=1)
    unit_rates = anchor_rates / speeds[:, None]
    start_direction_cosines = unit_rates @ unit_rates[0]
    consecutive_cosines = np.sum(unit_rates[1:] * unit_rates[:-1], axis=1)
    consecutive_turns = np.arccos(np.clip(consecutive_cosines, -1.0, 1.0))
    displacement = trajectory - trajectory[0]
    increments = np.diff(trajectory, axis=0)
    path_length = float(np.sum(np.linalg.norm(increments, axis=1)))
    endpoint_distance = float(np.linalg.norm(displacement[-1]))
    tortuosity = path_length / max(endpoint_distance, np.finfo(float).tiny)
    centered = displacement - np.mean(displacement, axis=0)
    singular_values = np.linalg.svd(centered, compute_uv=False)
    pod_energy = singular_values**2 / np.sum(singular_values**2)
    terminal_speed_ratio = float(speeds[-1] / speeds[0])
    cycle_return_fraction = float(
        np.min(np.linalg.norm(displacement[2:], axis=1))
        / max(path_length, np.finfo(float).tiny)
    )

    hermite_metrics = {}
    hermite_arrays = {}
    for stride in HERMITE_STRIDES:
        item, arrays = _hermite_replay(anchor_coordinates, anchor_rates, stride)
        hermite_metrics[str(stride)] = item
        for name, value in arrays.items():
            hermite_arrays[f"stride_{stride}__{name}"] = value
    passing_strides = [
        stride for stride in HERMITE_STRIDES if hermite_metrics[str(stride)]["passed"]
    ]
    maximum_passing_stride = max(passing_strides, default=0)

    open_path_gates = {
        "section_strictly_increasing": bool(np.all(np.diff(section) > 0.0)),
        "section_velocity_strictly_positive": bool(
            np.all(section_velocity > 0.0)
        ),
        "path_tortuosity": tortuosity,
        "path_tortuosity_passed": bool(tortuosity <= MAXIMUM_OPEN_PATH_TORTUOSITY),
        "first_pod_energy": float(pod_energy[0]),
        "first_pod_energy_passed": bool(
            pod_energy[0] >= MINIMUM_FIRST_POD_ENERGY
        ),
        "minimum_start_direction_cosine": float(np.min(start_direction_cosines)),
        "direction_alignment_passed": bool(
            np.min(start_direction_cosines) >= MINIMUM_START_DIRECTION_COSINE
        ),
        "terminal_speed_ratio": terminal_speed_ratio,
        "terminal_speed_remains_finite": bool(
            terminal_speed_ratio >= MINIMUM_OPEN_TERMINAL_SPEED_RATIO
        ),
        "maximum_validated_hermite_stride": int(maximum_passing_stride),
        "four_millisecond_transport_passed": bool(maximum_passing_stride >= 16),
    }
    open_path_supported = bool(
        all(
            (
                open_path_gates["section_strictly_increasing"],
                open_path_gates["section_velocity_strictly_positive"],
                open_path_gates["path_tortuosity_passed"],
                open_path_gates["first_pod_energy_passed"],
                open_path_gates["direction_alignment_passed"],
                open_path_gates["terminal_speed_remains_finite"],
                open_path_gates["four_millisecond_transport_passed"],
            )
        )
    )
    equilibrium_supported = bool(
        terminal_speed_ratio <= MAXIMUM_EQUILIBRIUM_TERMINAL_SPEED_RATIO
        and np.all(np.diff(speeds[-16:]) < 0.0)
    )
    cycle_supported = bool(
        parent_lock["summary"]["complete_cycle_observed"]
        and cycle_return_fraction <= MAXIMUM_CYCLE_RETURN_DISTANCE_FRACTION
    )
    source_audit = _source_audit()
    passed = bool(
        source_audit["truth_field_autonomous"]
        and open_path_supported
        and not cycle_supported
        and not equilibrium_supported
    )
    classification = CLASSIFICATION if passed else (
        "complete_cycle_asymptotic_architecture_remains_unresolved"
    )

    angle_from_start = np.arccos(np.clip(start_direction_cosines, -1.0, 1.0))
    forecasts = {
        "section_velocity_zero": [
            _linear_target_forecast(anchor_time, section_velocity, 0.0, count)
            for count in (16, 32, 64)
        ],
        "direction_orthogonal_to_start": [
            _linear_target_forecast(
                anchor_time, angle_from_start, 0.5 * np.pi, count
            )
            for count in (16, 32, 64)
        ],
    }
    metrics = {
        "schema_version": SCHEMA_VERSION,
        "work_package": WORK_PACKAGE,
        "classification": classification,
        "passed": passed,
        "source_audit": source_audit,
        "open_path_gates": open_path_gates,
        "cycle_closure_supported": cycle_supported,
        "equilibrium_closure_supported": equilibrium_supported,
        "wide_arclength_transport_supported": open_path_supported,
        "hermite_replay": hermite_metrics,
        "forecasts_are_diagnostic_only": True,
        "linear_forecasts": forecasts,
        "gate_values": {
            "trajectory_duration_seconds": float(trajectory_time[-1]),
            "trajectory_points": int(len(trajectory)),
            "exact_anchor_rates": int(len(anchor_rates)),
            "section_endpoint": float(section[-1]),
            "minimum_section_increment": float(np.min(np.diff(section))),
            "minimum_section_velocity_per_second": float(
                np.min(section_velocity)
            ),
            "initial_speed_per_second": float(speeds[0]),
            "terminal_speed_per_second": float(speeds[-1]),
            "terminal_speed_ratio": terminal_speed_ratio,
            "minimum_start_direction_cosine": float(
                np.min(start_direction_cosines)
            ),
            "net_direction_turn_radians": float(angle_from_start[-1]),
            "cumulative_direction_turn_radians": float(
                np.sum(consecutive_turns)
            ),
            "path_length": path_length,
            "endpoint_distance": endpoint_distance,
            "path_tortuosity": tortuosity,
            "first_pod_energy": float(pod_energy[0]),
            "second_pod_energy": float(pod_energy[1]),
            "cycle_return_distance_fraction": cycle_return_fraction,
            "maximum_validated_hermite_stride": int(maximum_passing_stride),
            "maximum_validated_hermite_duration_seconds": (
                maximum_passing_stride * MACRO_STEP_SECONDS
            ),
            "fixed_Q_calls": 0,
            "new_exact_free_field_calls": 0,
            "new_retractions": 0,
            "new_physical_time_advanced_seconds": 0.0,
        },
        "input_lock": {
            "parent_hashes": parent_lock["hashes"],
            "parent_classification": parent_lock["summary"]["classification"],
        },
    }
    arrays = {
        "trajectory_time_seconds": trajectory_time,
        "anchor_time_seconds": anchor_time,
        "section": section,
        "section_velocity_per_second": section_velocity,
        "anchor_speed_per_second": speeds,
        "start_direction_cosine": start_direction_cosines,
        "consecutive_direction_turn_radians": consecutive_turns,
        "trajectory_singular_values": singular_values,
        "trajectory_pod_energy": pod_energy,
        "trajectory_macro82": macro,
        **hermite_arrays,
    }
    return metrics, arrays


